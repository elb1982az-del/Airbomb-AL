#!/usr/bin/env bash
# Airbomb-Al — one-command installer for Kali NetHunter.
#
#   sudo ./install.sh
#
# Installs the engine, its dependencies, the airbomb-engine service wrapper and
# copies the APK to /sdcard/Download when one is present. It never enables monitor
# mode: the radio is left exactly as it was.
#
# Testing switches (no radio access, no service start):
#   AIRBOMB_SKIP_DEPS=1 AIRBOMB_NO_START=1 AIRBOMB_NO_SDCARD=1 AIRBOMB_DIR=/tmp/x ./install.sh
set -euo pipefail

APP_DIR="${AIRBOMB_DIR:-/opt/Airbomb-Al}"
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN="/usr/local/bin/airbomb-engine"

say()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "run as root (NetHunter: sudo ./install.sh)"

# ---------------------------------------------------------------- dependencies
say "Installing wireless tooling (aircrack-ng, iw, wireless-tools)"
if [ "${AIRBOMB_SKIP_DEPS:-0}" = "1" ]; then
    warn "AIRBOMB_SKIP_DEPS=1 — skipping package installation"
elif command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    if ! command -v airodump-ng >/dev/null 2>&1 || ! command -v iw >/dev/null 2>&1; then
        apt-get update -qq || warn "apt-get update failed; continuing with cached indexes"
    fi
    apt-get install -y --no-install-recommends \
        aircrack-ng iw wireless-tools iproute2 python3 ca-certificates \
        || warn "apt-get reported an error; checking tools individually"
else
    warn "apt-get not found; install aircrack-ng, iw, wireless-tools and python3 manually"
fi

missing=0
for tool in python3 iw airmon-ng airodump-ng aireplay-ng aircrack-ng; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        warn "missing: $tool"
        missing=1
    fi
done
[ "$missing" -eq 0 ] || warn "some tools are missing — scanning/capture may not work until installed"

# ---------------------------------------------------------------- backend files
say "Deploying engine to $APP_DIR"
mkdir -p "$APP_DIR/backend" "$APP_DIR/captures" "$APP_DIR/logs"

if [ -d "$SRC/backend" ]; then
    src_backend="$(readlink -f "$SRC/backend")"
    dst_backend="$(readlink -f "$APP_DIR/backend")"
    if [ "$src_backend" != "$dst_backend" ]; then
        cp -f "$SRC"/backend/airbomb_engine.py \
              "$SRC"/backend/protocol.md \
              "$SRC"/backend/requirements.txt \
              "$SRC"/backend/test_engine.py \
              "$APP_DIR/backend/" 2>/dev/null || true
    fi
else
    warn "no backend/ directory next to install.sh — engine not copied"
fi
chmod +x "$APP_DIR/backend/airbomb_engine.py" 2>/dev/null || true

# ---------------------------------------------------------------- service wrapper
say "Installing $BIN"
cat > "$BIN" <<EOF
#!/bin/sh
# Airbomb-Al engine control — generated by install.sh
APP_DIR="$APP_DIR"
PIDFILE="\$APP_DIR/logs/engine.pid"
LOG="\$APP_DIR/logs/engine.log"
PY="\$(command -v python3 || echo /usr/bin/python3)"
PORT="\${AIRBOMB_PORT:-8767}"

running() {
    [ -f "\$PIDFILE" ] || return 1
    pid="\$(cat "\$PIDFILE" 2>/dev/null)"
    [ -n "\$pid" ] && kill -0 "\$pid" 2>/dev/null
}

start() {
    if running; then
        echo "airbomb-engine already running (pid \$(cat "\$PIDFILE"))"
        return 0
    fi
    mkdir -p "\$APP_DIR/logs" "\$APP_DIR/captures"
    cd "\$APP_DIR/backend" || exit 1
    if command -v ss >/dev/null 2>&1 && ss -ltn 2>/dev/null | grep -q ":\$PORT "; then
        echo "port \$PORT is already in use — stop the other engine first" >&2
        return 1
    fi
    nohup "\$PY" airbomb_engine.py --port "\$PORT" >> "\$LOG" 2>&1 < /dev/null &
    echo \$! > "\$PIDFILE"
    sleep 1
    if running; then
        echo "airbomb-engine started (pid \$(cat "\$PIDFILE")) on 127.0.0.1:\$PORT"
    else
        echo "airbomb-engine failed to start; see \$LOG" >&2
        rm -f "\$PIDFILE"
        return 1
    fi
}

stop() {
    if ! running; then
        echo "airbomb-engine is not running"
        rm -f "\$PIDFILE"
        return 0
    fi
    pid="\$(cat "\$PIDFILE")"
    kill "\$pid" 2>/dev/null || true
    i=0
    while kill -0 "\$pid" 2>/dev/null && [ "\$i" -lt 10 ]; do
        sleep 0.5
        i=\$((i + 1))
    done
    kill -9 "\$pid" 2>/dev/null || true
    rm -f "\$PIDFILE"
    echo "airbomb-engine stopped"
}

status() {
    if running; then
        echo "airbomb-engine: running (pid \$(cat "\$PIDFILE"))"
        echo "endpoint:       127.0.0.1:\$PORT"
        echo "log:            \$LOG"
    else
        echo "airbomb-engine: stopped"
        return 1
    fi
}

case "\${1:-status}" in
    start)   start ;;
    stop)    stop ;;
    restart) stop; sleep 1; start ;;
    status)  status ;;
    logs)    tail -n 60 -f "\$LOG" ;;
    *)
        echo "usage: airbomb-engine {start|stop|restart|status|logs}" >&2
        exit 2
        ;;
esac
EOF
chmod 755 "$BIN"

# ---------------------------------------------------------------- APK
APK=""
for candidate in \
    "$SRC/Airbomb-Al.apk" \
    "$SRC/dist/Airbomb-Al.apk" \
    "$SRC/android/app/build/outputs/apk/release/app-release.apk" \
    "$SRC/android/app/build/outputs/apk/debug/app-debug.apk"
do
    if [ -f "$candidate" ]; then
        APK="$candidate"
        break
    fi
done

if [ -n "$APK" ]; then
    say "APK found: $APK"
    if [ "${AIRBOMB_NO_SDCARD:-0}" = "1" ]; then
        warn "AIRBOMB_NO_SDCARD=1 — skipping copy to /sdcard/Download"
    elif [ -d /sdcard/Download ] && cp -f "$APK" /sdcard/Download/Airbomb-Al.apk 2>/dev/null; then
        say "Copied to /sdcard/Download/Airbomb-Al.apk"
    else
        warn "could not write /sdcard/Download; install the APK manually"
    fi
else
    warn "no Airbomb-Al.apk found next to install.sh (build it with scripts/build_release.sh)"
fi

# ---------------------------------------------------------------- start engine
if [ "${AIRBOMB_NO_START:-0}" = "1" ]; then
    warn "AIRBOMB_NO_START=1 — engine not started (run: airbomb-engine start)"
else
    say "Starting the local engine"
    "$BIN" restart || warn "engine did not start; run: airbomb-engine logs"
fi

cat <<EOF

  Airbomb-Al is installed.

    engine   : $BIN start|stop|restart|status|logs
    endpoint : 127.0.0.1:8767 (loopback only)
    app      : /sdcard/Download/Airbomb-Al.apk  →  tap to install

  The radio is left in its current mode. Open the app, read the disclaimer,
  then use SCAN → Radio to switch an adapter to monitor mode when you are ready.

  ⚠️  FOR AUTHORIZED SECURITY TESTING AND EDUCATIONAL USE ONLY.

EOF
